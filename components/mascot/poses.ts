/**
 * Позы персонажа — по одной на секцию.
 *
 * Каждая поза это готовый рендер из присланного листа. Векторную сборку
 * на шарнирах пришлось убрать: при всей гибкости она читалась роботом,
 * а рендеры сохраняют мех, ткань и контровой свет оригинала.
 *
 * Разнообразие при четырёх картинках добираем зеркалом, масштабом,
 * положением в кадре и тем, с какой стороны стоит плита со словом.
 */

export type Pose = {
  /** Имя файла в public/mascot/. */
  src: "stand" | "point" | "back" | "arms";
  /** Отразить по горизонтали. */
  flip?: boolean;
  /** Доля высоты контейнера, которую занимает фигура. */
  scale: number;
  /** Сдвиг от центра контейнера в процентах его ширины и высоты. */
  x?: number;
  y?: number;
  /** Слово на плите. Без него плита не рисуется. */
  word?: string;
  /** Где стоит плита относительно фигуры. */
  slab?: {
    side: "left" | "right";
    /** Положение по вертикали в процентах высоты контейнера. */
    top: number;
    rotate?: number;
  };
};

